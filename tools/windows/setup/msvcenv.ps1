# Writes C:\msys64\etc\zlenv.sh: the environment vcvars64.bat sets, in bash
# form, plus the MSYS2 UCRT64 PATH. sshd's DefaultShell is MSYS2 bash, and a
# bash that sshd starts with a command reads ~/.bashrc -- under HOME, the
# Windows profile -- and not BASH_ENV, so that .bashrc sources this file: every
# `ssh zlwin <cmd>` has cl, link, make and UCRT64 gcc on PATH. BASH_ENV names
# it too, for a bash started any other way. The MSVC directories come before
# /usr/bin, where MSYS2's coreutils `link` would otherwise shadow MSVC's
# link.exe. Re-run after a Build Tools upgrade (winvm.sh update-golden does).
$ErrorActionPreference = 'Stop'
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'no Visual Studio install with the x64 C tools' }
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'

function EnvOf([string]$cmd) {
    $h = @{}
    # cmd.exe by its path: under ssh MSYS2's /usr/bin, which has a `cmd` script,
    # comes first on PATH
    & "$env:SystemRoot\System32\cmd.exe" /c "$cmd >nul 2>&1 && set" | ForEach-Object {
        if ($_ -match '^([^=]+)=(.*)$') { $h[$matches[1]] = $matches[2] }
    }
    return $h
}
$before = EnvOf 'ver'
$after = EnvOf "call `"$vcvars`""

function Posix([string]$p) {
    if ($p -match '^([A-Za-z]):\\?(.*)$') {
        return '/' + $matches[1].ToLower() + '/' + ($matches[2] -replace '\\', '/').TrimEnd('/')
    }
    return $p
}
function Quote([string]$v) { return "'" + ($v -replace "'", "'\''") + "'" }

$out = @('# generated by C:\zl\setup\msvcenv.ps1 -- do not edit',
         '[ -n "$ZLENV" ] && return 0',
         'export ZLENV=1')
$oldPath = $before['Path'] -split ';'
$msvcDirs = ($after['Path'] -split ';') | Where-Object { $_ -and ($oldPath -notcontains $_) } | ForEach-Object { Posix $_ }
foreach ($k in ($after.Keys | Sort-Object)) {
    if ($k -eq 'Path' -or $k -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { continue }
    if ($before.ContainsKey($k) -and $before[$k] -eq $after[$k]) { continue }
    $out += "export $k=$(Quote $after[$k])"
}
$out += 'export MSYSTEM=UCRT64'
$out += "export PATH=$(Quote (($msvcDirs + @('/ucrt64/bin', '/usr/local/bin', '/usr/bin', '/bin')) -join ':')):`"`$PATH`""
[IO.File]::WriteAllText('C:\msys64\etc\zlenv.sh', (($out -join "`n") + "`n"))
$rc = Join-Path $env:USERPROFILE '.bashrc'
New-Item -ItemType Directory -Force (Split-Path $rc) | Out-Null
if (-not (Test-Path $rc) -or -not (Select-String -Quiet -Path $rc -Pattern 'zlenv.sh')) {
    Add-Content -Path $rc -Value '. /etc/zlenv.sh'
}
Write-Output "zlenv.sh written from $vcvars"
