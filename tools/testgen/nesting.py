# generate the nesting fixtures:
#   errors/nesting_limit.z          a chain at the limit, then one a link past it
#   emitc_corpus/nesting_deep.z     each nested or chained shape, 100 levels deep,
#                                   with its golden
import sys

LIMIT = 500
# a function's definition is level 1 and a statement of its body level 2
INSIDE = LIMIT - 2
DEEP = 100


def chain(n):
    return '1' + ' + 1' * n


limit = '''# An expression may be nested or chained %d levels deep (nestingLimit). A
# function's definition is one level and a statement of its body another, so
# the sum in `atLimit`, with %d operators, is the deepest one a body can hold.
# The sum in `pastLimit` has one more.
# Generated by tools/testgen/nesting.py.
atLimit: function out i64 is {
    x: %s
    return x
}

pastLimit: function out i64 is {
    x: %s
    return x
}

main: function is {
    print "\\{atLimit} \\{pastLimit}"
}
''' % (LIMIT, INSIDE, chain(INSIDE), chain(INSIDE + 1))
open(sys.argv[1] + '/errors/nesting_limit.z', 'w').write(limit)

n = DEEP
blocks = ''.join('    if n > 0 then {\n' for _ in range(n)) + '    r = n + 1\n' + '    }\n' * n
arms = ''.join(' else if n == %d then {\n        r = %d\n    }' % (i, i) for i in range(1, n))
deep = '''# Each shape that nests or chains, %d levels deep: the checker and the emitter
# follow a tree level by level, and every C compiler must take what they write.
# Generated by tools/testgen/nesting.py.
one: function {a: i64} out i64 is {
    return a
}

parens: function out i64 is {
    x: %s
    return x
}

sum: function out i64 is {
    x: %s
    return x
}

text: function out u64 is {
    s: "a".string%s
    return s.length
}

copies: function out u64 is {
    s: "ab".string
    t: s%s
    return t.length
}

blocks: function {n: i64} out i64 is {
    r: 0
%s    return r
}

arms: function {n: i64} out i64 is {
    r: 0
    if n == 0 then {
        r = 1000
    }%s else {
        r = 2000
    }
    return r
}

args: function out i64 is {
    x: %s
    return x
}

main: function is {
    print "\\{parens} \\{sum} \\{text} \\{copies}"
    print "\\{blocks n: 1} \\{arms n: 0} \\{arms n: %d} \\{arms n: %d} \\{args}"
}
''' % (n, '(' * n + '1' + ')' * n, chain(n), ' + "b"' * n, '.copy' * n, blocks, arms,
       'one a: (' * n + '7' + ')' * n, n - 1, n)
open(sys.argv[1] + '/emitc_corpus/nesting_deep.z', 'w').write(deep)
golden = '1 %d %d 2\n2 1000 %d 2000 7\n' % (n + 1, n + 1, n - 1)
open(sys.argv[1] + '/run_golden/nesting_deep.out', 'w').write(golden)
