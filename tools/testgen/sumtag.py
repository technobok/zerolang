# generate the fixtures for the number of arms a tag can number:
#   errors/sum_tag_too_narrow.z    257 arms on the default tag, a u8
#   emitc_corpus/sum_tag_wide.z    256 arms on the default tag and 300 on a
#                                  u16 tag, each matched to its last arm, with
#                                  its golden
import sys


def variant(name, n, tag):
    arms = ''.join('    a%d: null\n' % i for i in range(n))
    tail = '} as {\n    tag: %s.tag\n}\n' % tag if tag else '}\n'
    return '%s: variant {\n%s%s' % (name, arms, tail)


def pick(fn, name, n):
    cases = ''.join(' case a%d then {\n        r = %d\n    }' % (i, i) for i in range(n))
    return ('%s: function {v: %s} out i64 is {\n    r: 0\n    match (\n        v\n    )%s\n'
            '    return r\n}\n' % (fn, name, cases))


narrow = '''# A variant numbers its arms from 0 in its tag, a u8 unless the `as` section
# declares another type. 257 arms are one more than a u8 numbers.
# Generated by tools/testgen/sumtag.py.
''' + variant('Many', 257, '') + '''
main: function is {
    m: Many.a256
    print "made"
}
'''
open(sys.argv[1] + '/errors/sum_tag_too_narrow.z', 'w').write(narrow)

wide = '''# The most arms the default tag numbers, 256, and 300 arms on a declared
# `u16.tag`: the last arm of each is told from the first.
# Generated by tools/testgen/sumtag.py.
''' + variant('Full', 256, '') + '\n' + variant('Wide', 300, 'u16') + '\n' + pick(
    'pickFull', 'Full', 256) + '\n' + pick('pickWide', 'Wide', 300) + '''
main: function is {
    print "\\{pickFull v: Full.a255} \\{pickFull v: Full.a0} \\{pickWide v: Wide.a299} \\{pickWide v: Wide.a256}"
}
'''
open(sys.argv[1] + '/emitc_corpus/sum_tag_wide.z', 'w').write(wide)
open(sys.argv[1] + '/run_golden/sum_tag_wide.out', 'w').write('255 0 299 256\n')
